int blink_font_measure_text(const char* text, int font_size, int letter_spacing) {
    if (!text || *text == '\0') return 0;
    if (font_size <= 0) font_size = BLINK_FONT_BASE_HEIGHT;

    int char_w = (font_size * BLINK_FONT_BASE_WIDTH + BLINK_FONT_BASE_HEIGHT / 2) / BLINK_FONT_BASE_HEIGHT;
    if (char_w < 1) char_w = 1;

    int max_line_width = 0;
    int current_chars = 0;

    const char* p = text;
    while (*p) {
        if (*p == '\r') {
            p++;
            continue;
        }
        if (*p == '\n') {
            int line_w = (current_chars > 0) ? (current_chars * char_w + (current_chars - 1) * letter_spacing) : 0;
            if (line_w < 0) line_w = 0;
            if (line_w > max_line_width) max_line_width = line_w;
            current_chars = 0;
            p++;
            continue;
        }
        if (*p == '\t') {
            current_chars += 4;
            p++;
            continue;
        }
        current_chars++;
        p++;
    }

    int line_w = (current_chars > 0) ? (current_chars * char_w + (current_chars - 1) * letter_spacing) : 0;
    if (line_w < 0) line_w = 0;
    if (line_w > max_line_width) max_line_width = line_w;

    return max_line_width;
}

void blink_font_draw_text(uint32_t* fb, int fb_w, int fb_h,
                         int x, int y,
                         const char* text, uint32_t color,
                         int font_size, int letter_spacing) {
    if (!fb || fb_w <= 0 || fb_h <= 0 || !text || *text == '\0') return;
    if (!s_initialized) blink_font_init();
    if (font_size <= 0) font_size = BLINK_FONT_BASE_HEIGHT;

    int char_w = (font_size * BLINK_FONT_BASE_WIDTH + BLINK_FONT_BASE_HEIGHT / 2) / BLINK_FONT_BASE_HEIGHT;
    if (char_w < 1) char_w = 1;
    int line_h = font_size + (font_size >= 16 ? 2 : 1);

    int cur_x = x;
    int cur_y = y;

    const char* p = text;
    while (*p) {
        if (*p == '\r') {
            p++;
            continue;
        }
        if (*p == '\n') {
            cur_x = x;
            cur_y += line_h;
            p++;
            continue;
        }
        if (*p == '\t') {
            cur_x += (char_w + letter_spacing) * 4;
            p++;
            continue;
        }

        render_glyph_clipped(fb, fb_w, 0, 0, fb_w, fb_h, cur_x, cur_y, *p, color, font_size);
        cur_x += char_w + letter_spacing;
        p++;
    }
}

void blink_font_draw_text_box(uint32_t* fb, int fb_w, int fb_h,
                             int x, int y, int w, int h,
                             const char* text, uint32_t color,
                             int font_size, int align) {
    if (!fb || fb_w <= 0 || fb_h <= 0 || !text || *text == '\0' || w <= 0 || h <= 0) return;
    if (!s_initialized) blink_font_init();
    if (font_size <= 0) font_size = BLINK_FONT_BASE_HEIGHT;

    int clip_x0 = (x < 0) ? 0 : x;
    int clip_y0 = (y < 0) ? 0 : y;
    int clip_x1 = (x + w > fb_w) ? fb_w : (x + w);
    int clip_y1 = (y + h > fb_h) ? fb_h : (y + h);
    if (clip_x0 >= clip_x1 || clip_y0 >= clip_y1) return;

    int char_w = (font_size * BLINK_FONT_BASE_WIDTH + BLINK_FONT_BASE_HEIGHT / 2) / BLINK_FONT_BASE_HEIGHT;
    if (char_w < 1) char_w = 1;
    int line_h = font_size + (font_size >= 16 ? 2 : 1);

    #define MAX_BOX_LINES 256
    typedef struct {
        const char* start;
        int len;
        int width;
    } BoxLine;

    BoxLine lines[MAX_BOX_LINES];
    int line_count = 0;

    const char* p = text;
    while (*p && line_count < MAX_BOX_LINES) {
        if (*p == '\r') { p++; continue; }

        const char* para_start = p;
        while (*p && *p != '\n' && *p != '\r') p++;
        const char* para_end = p;
        if (*p == '\r' && *(p + 1) == '\n') p += 2;
        else if (*p == '\n' || *p == '\r') p++;

        const char* word_p = para_start;
        const char* line_start = word_p;
        int cur_line_len = 0;

        while (word_p < para_end && line_count < MAX_BOX_LINES) {
            const char* next_space = word_p;
            while (next_space < para_end && *next_space != ' ') next_space++;
            int word_len = (int)(next_space - word_p);

            int test_len = (cur_line_len == 0) ? word_len : (cur_line_len + 1 + word_len);
            int test_w = test_len * char_w;

            if (test_w <= w || cur_line_len == 0) {
                cur_line_len = test_len;
                word_p = next_space;
                if (word_p < para_end && *word_p == ' ') word_p++;
            } else {
                lines[line_count].start = line_start;
                lines[line_count].len = cur_line_len;
                lines[line_count].width = cur_line_len * char_w;
                line_count++;

                line_start = word_p;
                cur_line_len = 0;
            }
        }

        if (cur_line_len > 0 && line_count < MAX_BOX_LINES) {
            lines[line_count].start = line_start;
            lines[line_count].len = cur_line_len;
            lines[line_count].width = cur_line_len * char_w;
            line_count++;
        } else if (para_start == para_end && line_count < MAX_BOX_LINES) {
            lines[line_count].start = para_start;
            lines[line_count].len = 0;
            lines[line_count].width = 0;
            line_count++;
        }
    }

    if (line_count == 0) return;

    int total_text_h = (line_count > 1) ? ((line_count - 1) * line_h + font_size) : font_size;
    int cur_y = y;
    if (h > total_text_h) {
        cur_y = y + (h - total_text_h) / 2;
    }

    for (int i = 0; i < line_count; ++i) {
        int cur_x = x;
        if (align == BLINK_FONT_ALIGN_CENTER) {
            cur_x = x + (w - lines[i].width) / 2;
        } else if (align == BLINK_FONT_ALIGN_RIGHT) {
            cur_x = x + w - lines[i].width;
        }

        for (int c_idx = 0; c_idx < lines[i].len; ++c_idx) {
            char ch = lines[i].start[c_idx];
            render_glyph_clipped(fb, fb_w, clip_x0, clip_y0, clip_x1, clip_y1,
                                 cur_x, cur_y, ch, color, font_size);
            cur_x += char_w;
        }
        cur_y += line_h;
    }
}
