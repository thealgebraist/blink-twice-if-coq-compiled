/* ========================================================================= */
/* Precomputed Subpixel Coverage & Alpha Blending Tables                     */
/* ========================================================================= */

static bool s_initialized = false;
static uint8_t s_alpha_blend_table[256][256];
static uint8_t s_subpixel_fractional_table[5][256];
static uint8_t s_subpixel_lcd_table[256][3];

void blink_font_init(void) {
    if (s_initialized) return;

    /* Precompute alpha blend LUT: table[alpha][val] = (alpha * val + 127) / 255 */
    for (int a = 0; a < 256; ++a) {
        for (int v = 0; v < 256; ++v) {
            s_alpha_blend_table[a][v] = (uint8_t)((a * v + 127) / 255);
        }
    }

    /* Precompute subpixel fractional coverage weights (phases: 0/4, 1/4, 2/4, 3/4, 4/4) */
    for (int p = 0; p <= 4; ++p) {
        for (int c = 0; c < 256; ++c) {
            s_subpixel_fractional_table[p][c] = (uint8_t)((c * p + 2) / 4);
        }
    }

    /* Precompute LCD subpixel coverage distributions (RGB stripe) */
    for (int c = 0; c < 256; ++c) {
        s_subpixel_lcd_table[c][0] = (uint8_t)((c * 85 + 128) / 255); /* R */
        s_subpixel_lcd_table[c][1] = (uint8_t)c;                       /* G */
        s_subpixel_lcd_table[c][2] = (uint8_t)((c * 85 + 128) / 255); /* B */
    }

    s_initialized = true;
}

uint8_t blink_font_get_glyph_pixel(char c, int gx, int gy) {
    if (gx < 0 || gx >= BLINK_FONT_BASE_WIDTH || gy < 0 || gy >= BLINK_FONT_BASE_HEIGHT) return 0;
    int idx = (int)(unsigned char)c - BLINK_FONT_ASCII_START;
    if (idx < 0 || idx >= BLINK_FONT_NUM_GLYPHS) return 0;
    return s_glyph_atlas_8x16[idx][gy][gx];
}

uint8_t blink_font_get_subpixel_coverage(uint8_t c0, uint8_t c1, int phase_4th) {
    if (!s_initialized) blink_font_init();
    if (phase_4th < 0) phase_4th = 0;
    if (phase_4th > 4) phase_4th = 4;
    uint8_t w0 = s_subpixel_fractional_table[4 - phase_4th][c0];
    uint8_t w1 = s_subpixel_fractional_table[phase_4th][c1];
    int sum = (int)w0 + (int)w1;
    return (sum > 255) ? 255 : (uint8_t)sum;
}

/* ========================================================================= */
/* High Performance Porter-Duff Alpha Compositor                             */
/* ========================================================================= */

static inline uint32_t blend_pixel(uint32_t dst_pixel, uint32_t src_color, uint8_t coverage) {
    if (coverage == 0) return dst_pixel;

    uint32_t src_a = (src_color >> 24) & 0xFF;
    if (src_a == 0) src_a = 255; /* Default to fully opaque if alpha channel is 0 */

    uint32_t eff_a = s_alpha_blend_table[coverage][src_a];
    if (eff_a == 0) return dst_pixel;

    uint32_t src_r = (src_color >> 16) & 0xFF;
    uint32_t src_g = (src_color >> 8) & 0xFF;
    uint32_t src_b = src_color & 0xFF;

    if (eff_a == 255) {
        return (0xFF000000U) | (src_r << 16) | (src_g << 8) | src_b;
    }

    uint32_t dst_a = (dst_pixel >> 24) & 0xFF;
    uint32_t dst_r = (dst_pixel >> 16) & 0xFF;
    uint32_t dst_g = (dst_pixel >> 8) & 0xFF;
    uint32_t dst_b = dst_pixel & 0xFF;

    uint32_t inv_a = 255 - eff_a;

    uint32_t out_r = s_alpha_blend_table[eff_a][src_r] + s_alpha_blend_table[inv_a][dst_r];
    uint32_t out_g = s_alpha_blend_table[eff_a][src_g] + s_alpha_blend_table[inv_a][dst_g];
    uint32_t out_b = s_alpha_blend_table[eff_a][src_b] + s_alpha_blend_table[inv_a][dst_b];
    uint32_t out_a = eff_a + s_alpha_blend_table[inv_a][dst_a];
    if (out_a > 255) out_a = 255;

    return (out_a << 24) | (out_r << 16) | (out_g << 8) | out_b;
}

/* ========================================================================= */
/* Glyph Rasterization Kernel with Clipping & Subpixel Bilinear Resampling    */
/* ========================================================================= */

static void render_glyph_clipped(uint32_t* fb, int fb_w,
                                 int clip_x0, int clip_y0, int clip_x1, int clip_y1,
                                 int gx_pos, int gy_pos, char c, uint32_t color, int font_size) {
    int glyph_idx = (int)(unsigned char)c - BLINK_FONT_ASCII_START;
    if (glyph_idx < 0 || glyph_idx >= BLINK_FONT_NUM_GLYPHS) {
        if (c == ' ' || c == '\t' || c == '\n' || c == '\r') return;
        glyph_idx = (int)'?' - BLINK_FONT_ASCII_START;
        if (glyph_idx < 0 || glyph_idx >= BLINK_FONT_NUM_GLYPHS) return;
    }

    const uint8_t (*glyph)[8] = s_glyph_atlas_8x16[glyph_idx];

    if (font_size == BLINK_FONT_BASE_HEIGHT) {
        /* Direct 1:1 native rasterization */
        int y_start = (gy_pos < clip_y0) ? clip_y0 : gy_pos;
        int y_end   = (gy_pos + 16 > clip_y1) ? clip_y1 : (gy_pos + 16);
        int x_start = (gx_pos < clip_x0) ? clip_x0 : gx_pos;
        int x_end   = (gx_pos + 8 > clip_x1) ? clip_x1 : (gx_pos + 8);

        if (y_start >= y_end || x_start >= x_end) return;

        for (int py = y_start; py < y_end; ++py) {
            int gy = py - gy_pos;
            uint32_t* row = fb + (size_t)py * (size_t)fb_w;
            for (int px = x_start; px < x_end; ++px) {
                int gx = px - gx_pos;
                uint8_t cov = glyph[gy][gx];
                if (cov > 0) {
                    row[px] = blend_pixel(row[px], color, cov);
                }
            }
        }
    } else {
        /* Scaled rasterization with subpixel bilinear filtering */
        int char_w = (font_size * BLINK_FONT_BASE_WIDTH + BLINK_FONT_BASE_HEIGHT / 2) / BLINK_FONT_BASE_HEIGHT;
        if (char_w < 1) char_w = 1;
        int char_h = font_size;

        int y_start = (gy_pos < clip_y0) ? clip_y0 : gy_pos;
        int y_end   = (gy_pos + char_h > clip_y1) ? clip_y1 : (gy_pos + char_h);
        int x_start = (gx_pos < clip_x0) ? clip_x0 : gx_pos;
        int x_end   = (gx_pos + char_w > clip_x1) ? clip_x1 : (gx_pos + char_w);

        if (y_start >= y_end || x_start >= x_end) return;

        for (int py = y_start; py < y_end; ++py) {
            int dy = py - gy_pos;
            int sy_fp = (dy * 16 * 256) / char_h;
            int gy = sy_fp >> 8;
            int fy = sy_fp & 0xFF;
            int gy1 = (gy + 1 < 16) ? (gy + 1) : 15;

            uint32_t* row = fb + (size_t)py * (size_t)fb_w;
            for (int px = x_start; px < x_end; ++px) {
                int dx = px - gx_pos;
                int sx_fp = (dx * 8 * 256) / char_w;
                int gx = sx_fp >> 8;
                int fx = sx_fp & 0xFF;
                int gx1 = (gx + 1 < 8) ? (gx + 1) : 7;

                uint32_t c00 = glyph[gy][gx];
                uint32_t c10 = glyph[gy][gx1];
                uint32_t c01 = glyph[gy1][gx];
                uint32_t c11 = glyph[gy1][gx1];

                uint32_t top = c00 * (256 - fx) + c10 * fx;
                uint32_t bot = c01 * (256 - fx) + c11 * fx;
                uint32_t cov = (top * (256 - fy) + bot * fy + 32768) >> 16;
                if (cov > 255) cov = 255;
                if (cov > 0) {
                    row[px] = blend_pixel(row[px], color, (uint8_t)cov);
                }
            }
        }
    }
}

